"""
The distance rasters generated by make_distance_rasters.py are oversized; clip them to the boundary,
then mosaic.
"""

import argparse
import os
import math
import numpy as np
import rasterio
from rasterio.mask import mask as rio_mask
import fiona
from shapely.geometry import shape as shp_shape, mapping as shp_mapping
from shapely.ops import transform as shp_transform, unary_union
from pyproj import CRS, Transformer


def load_and_reproject_geometries(shapefile_path: str, target_crs: CRS, dissolve: bool, buffer_dist: float):
    """
    Read a shapefile and project its geometries to the target CRS (typically the raster's CRS).
    Optional: dissolve multiple geometries into one; buffer in target-CRS units.
    Returns a list of GeoJSON-style geometries (suitable for rasterio.mask.mask).
    """
    with fiona.open(shapefile_path, "r") as src:
        if src.crs_wkt:
            source_crs = CRS.from_wkt(src.crs_wkt)
        elif src.crs:
            source_crs = CRS.from_user_input(src.crs)
        else:
            raise ValueError("Shapefile has no CRS; cannot reproject.")

        need_reproject = not source_crs.equals(target_crs)
        transformer = Transformer.from_crs(source_crs, target_crs, always_xy=True) if need_reproject else None

        geoms = []
        for feat in src:
            if not feat.get("geometry"):
                continue
            geom = shp_shape(feat["geometry"])
            if need_reproject:
                geom = shp_transform(transformer.transform, geom)
            if buffer_dist and not math.isclose(buffer_dist, 0.0):
                geom = geom.buffer(buffer_dist)
            geoms.append(geom)

    if not geoms:
        raise ValueError("Shapefile has no valid geometry.")

    if dissolve:
        geoms = [unary_union(geoms)]

    return [shp_mapping(g) for g in geoms]


def decide_nodata(profile):
    """Prefer the source raster's nodata; otherwise pick a reasonable default by dtype."""
    if profile.get("nodata") is not None:
        return profile["nodata"]

    dtype = profile.get("dtype", "float32")
    if np.issubdtype(np.dtype(dtype), np.floating):
        return -9999.0
    return 0


def clip_raster_by_shapefile(
    input_tif: str,
    shapefile_path: str,
    output_tif: str,
    invert: bool = False,
    crop: bool = True,
    all_touched: bool = False,
    dissolve: bool = False,
    buffer_dist: float = 0.0,
):
    """
    Clip a GeoTIFF with a shapefile and write a new file.
    - invert: invert selection (keep the area outside the polygon)
    - crop: crop to the geometry's bounding box (reduces output size)
    - all_touched: include pixels touched by the geometry boundary (a more "lenient" mask)
    - dissolve: dissolve multiple geometries into one before clipping
    - buffer_dist: buffer distance applied to the geometry, in target CRS (i.e. raster CRS) units
    """
    with rasterio.open(input_tif) as src:
        target_crs = src.crs
        if target_crs is None:
            raise ValueError("Input raster has no CRS; cannot align with the shapefile.")

        shapes = load_and_reproject_geometries(
            shapefile_path=shapefile_path,
            target_crs=target_crs,
            dissolve=dissolve,
            buffer_dist=buffer_dist,
        )

        nodata_value = decide_nodata(src.profile)

        clipped, out_transform = rio_mask(
            src,
            shapes=shapes,
            all_touched=all_touched,
            invert=invert,
            crop=crop,
            nodata=nodata_value,
            filled=True,
        )

        profile = src.profile.copy()
        profile.update(
            height=clipped.shape[1],
            width=clipped.shape[2],
            transform=out_transform,
            nodata=nodata_value,
            compress="lzw",
            tiled=True,
        )

        # For float data, set predictor=3 to improve compression
        if np.issubdtype(np.dtype(profile["dtype"]), np.floating):
            profile["predictor"] = 3

        os.makedirs(os.path.dirname(os.path.abspath(output_tif)), exist_ok=True)
        with rasterio.open(output_tif, "w", **profile) as dst:
            dst.write(clipped)


def parse_args():
    ap = argparse.ArgumentParser(description="Clip a GeoTIFF with a shapefile and output a new file")
    ap.add_argument("--input", default='/mnt/raid/user/wildfire_dataset/self_built_materials/osm_map/canada-distance/distance_water.tif', help="Input GeoTIFF path")
    ap.add_argument("--shapefile", default='/mnt/raid/user/wildfire_dataset/self_built_materials/bc_boundary/british_columnbia_no_crs_boundingBox.shp', help="Input shapefile path (.shp or other fiona-supported format)")
    ap.add_argument("--output", default='/mnt/raid/user/wildfire_dataset/self_built_materials/osm_map/canada-distance/distance_water_cropped.tif', help="Output GeoTIFF path")
    ap.add_argument("--invert", action="store_true", help="Invert selection (keep the area outside the geometry)")
    ap.add_argument("--no-crop", dest="crop", action="store_false", help="Do not crop to the geometry's bounding box")
    ap.add_argument("--all-touched", action="store_true", help="Pixels touching the geometry boundary are included in the mask")
    ap.add_argument("--dissolve", action="store_true", help="Dissolve multiple geometries into one before clipping")
    ap.add_argument("--buffer", type=float, default=0.0, help="Buffer distance applied to the geometry in target-CRS units (default 0)")
    ap.set_defaults(crop=True)
    return ap.parse_args()


def main():
    args = parse_args()
    clip_raster_by_shapefile(
        input_tif=args.input,
        shapefile_path=args.shapefile,
        output_tif=args.output,
        invert=args.invert,
        crop=args.crop,
        all_touched=args.all_touched,
        dissolve=args.dissolve,
        buffer_dist=args.buffer,
    )
    print(f"Generated: {args.output}")


if __name__ == "__main__":
    main()