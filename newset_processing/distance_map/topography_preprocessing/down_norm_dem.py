def _affine_to_gdal_gt(transform: Affine) -> tuple[float, float, float, float, float, float]:
    return (transform.c, transform.a, transform.b, transform.f, transform.d, transform.e)


def _band_nodata_mask(arr: np.ndarray, nodata: float | None) -> np.ndarray:
    m = ~np.isfinite(arr)
    if nodata is not None:
        m |= np.isclose(arr, np.float32(nodata), equal_nan=True)
    return m


def nodata_list_for_first_joint_rule(
    nodata_per_band: list[float | None],
    scale: float,
) -> list[float | None]:
    """
    Per-band nodata used by the first combined NoData rule pass.

    - scale > 1: bands 2-7 will be recomputed, so only Band 1 (DEM) keeps numeric-nodata matching; other bands only treat NaN as invalid,
      avoiding slope/hillshade=0 or TPI/TWI=0 colliding with nodata=0 and turning entire pixels (including the DEM) into NaN.
    - scale <= 1: still disable numeric nodata for bands 6/7 (TPI/TWI are often 0 and legitimate).
    """
    n = len(nodata_per_band)
    out = list(nodata_per_band)
    if scale > 1.0:
        for i in range(1, n):
            out[i] = None
    else:
        for i in (5, 6):
            if i < n:
                out[i] = None
    return out


def apply_multi_band_nodata_rule(
    bands: list[np.ndarray],
    nodata_per_band: list[float | None],
    *,
    min_bands_nodata: int = 2,
    aspect_sin_cos_pair: tuple[int, int] | None = (2, 3),
) -> list[np.ndarray]:
    """
    aspect_sin_cos_pair:
      Aspect sin/cos are generated by the same rules; in flat regions (e.g. -1), both are typically NaN at once.
      Counting them as two separate invalid bands at min_bands_nodata=2 would mistakenly mark the entire pixel as invalid
      and wipe DEM/TPI/TWI as well. Combining them into a single "aspect layer" counts only once.
      Set to None to restore the legacy behavior (per-band counting).
    """
    if not bands:
        return bands
    n = len(bands)
    if len(nodata_per_band) != n:
        raise ValueError("nodata_per_band must have the same length as bands")

    stacks = np.stack([b.astype(np.float64, copy=False) for b in bands], axis=0)
    per = np.zeros(stacks.shape[1:], dtype=np.int32)
    skip: set[int] = set()
    merged_aspect: tuple[int, int] | None = None
    if aspect_sin_cos_pair is not None:
        ia, ib = aspect_sin_cos_pair
        if 0 <= ia < n and 0 <= ib < n and ia != ib:
            skip.update((ia, ib))
            merged_aspect = (ia, ib)
    for i in range(n):
        if i in skip:
            continue
        per += _band_nodata_mask(stacks[i], nodata_per_band[i]).astype(np.int32)
    if merged_aspect is not None:
        ia, ib = merged_aspect
        ma = _band_nodata_mask(stacks[ia], nodata_per_band[ia])
        mb = _band_nodata_mask(stacks[ib], nodata_per_band[ib])
        per += (ma | mb).astype(np.int32)

    bad = per >= min_bands_nodata
    if not np.any(bad):
        return [b.copy() if b.dtype != np.float32 else b for b in bands]

    out = []
    for i in range(n):
        a = stacks[i].astype(np.float32, copy=True)
        a[bad] = np.nan
        out.append(a)
    return out


def _band_label(src_desc: tuple | None, index: int) -> str:
    if src_desc and index < len(src_desc) and src_desc[index]:
        return str(src_desc[index])
    if index < len(dn.DEFAULT_STACK_BAND_NAMES):
        return dn.DEFAULT_STACK_BAND_NAMES[index]
    return f"Band{index + 1}"


def read_stack_all_bands(
    path: Path,
) -> tuple[list[np.ndarray], dict, float | None, int, tuple, list[float | None], Affine, Any]:
    with rasterio.open(path) as src:
        count = src.count
        prof = src.profile.copy()
        nod = src.nodata
        nv = getattr(src, "nodatavals", None)
        desc = src.descriptions
        tf = src.transform
        crs = src.crs
        bands = []
        nodata_list: list[float | None] = []
        for b in range(1, count + 1):
            arr = src.read(b).astype(np.float32, copy=False)
            nd = nv[b - 1] if nv is not None and b - 1 < len(nv) else nod
            nodata_list.append(nd)
            if nd is not None:
                arr = arr.copy()
                arr[np.isclose(arr, np.float32(nd), equal_nan=True)] = np.nan
            bands.append(arr)
        return (
            bands,
            prof,
            nod,
            count,
            tuple(desc) if desc else tuple(),
            nodata_list,
            tf,
            crs,
        )


def reproject_band_to_shape(
    arr: np.ndarray,
    src_transform: Affine,
    src_crs: Any,
    out_h: int,
    out_w: int,
    dst_transform: Affine,
) -> np.ndarray:
    dst = np.empty((out_h, out_w), dtype=np.float32)
    reproject(
        source=arr,
        destination=dst,
        src_transform=src_transform,
        src_crs=src_crs,
        dst_transform=dst_transform,
        dst_crs=src_crs,
        resampling=Resampling.bilinear,
        src_nodata=np.nan,
        dst_nodata=np.nan,
    )
    return dst


def demprocess_to_array(
    src_arr: np.ndarray,
    crs_wkt: str,
    transform: Affine,
    mode: str,
    options: list[str],
) -> np.ndarray:
    if gdal is None:
        raise RuntimeError(
            "Downsampling and recomputing slope/aspect requires osgeo.gdal; please install the GDAL Python bindings."
        ) from _GDAL_IMPORT_ERROR
    vsipath = "/vsimem/dem_base_dn.tif"
    h, w = src_arr.shape
    drv = gdal.GetDriverByName("GTiff")
    ds = drv.Create(vsipath, w, h, 1, gdal.GDT_Float32)
    if crs_wkt:
        ds.SetProjection(crs_wkt)
    ds.SetGeoTransform(_affine_to_gdal_gt(transform))
    ds.GetRasterBand(1).WriteArray(np.asarray(src_arr, dtype=np.float32))
    ds.FlushCache()
    out_path = f"/vsimem/demproc_{mode}_dn.tif"
    gdal.DEMProcessing(out_path, ds, mode, options=options)
    ds = None
    out_ds = gdal.Open(out_path, gdal.GA_ReadOnly)
    if out_ds is None:
        gdal.Unlink(vsipath)
        raise RuntimeError(f"DEMProcessing failed: {mode}")
    arr = out_ds.GetRasterBand(1).ReadAsArray()
    out_ds = None
    gdal.Unlink(vsipath)
    gdal.Unlink(out_path)
    return arr.astype(np.float32)


def aspect_deg_to_sin_cos(
    aspect_deg: np.ndarray, dem_valid: np.ndarray
) -> tuple[np.ndarray, np.ndarray]:
    """Consistent with dems_cal: aspect (deg) -> sin/cos; flat -1 or out-of-range becomes NaN."""
    a = aspect_deg.astype(np.float64, copy=False)
    valid_aspect = (
        dem_valid & np.isfinite(a) & (a >= 0.0) & (a <= 360.0)
    )
    sinv = np.full(a.shape, np.nan, dtype=np.float32)
    cosv = np.full(a.shape, np.nan, dtype=np.float32)
    theta = np.deg2rad(a)
    sinv[valid_aspect] = np.sin(theta[valid_aspect]).astype(np.float32)
    cosv[valid_aspect] = np.cos(theta[valid_aspect]).astype(np.float32)
    return sinv, cosv


def downsample_stack(
    bands: list[np.ndarray],
    src_transform: Affine,
    src_crs: Any,
    raw_count: int,
    scale: float,
    args: argparse.Namespace,
) -> tuple[list[np.ndarray], Affine, int, int, dict[str, Any]]:
    """
    scale > 1: DEM bilinear; bands 2-5 use GDAL DEMProcessing (-s consistent with dems_cal);
    bands 6/7 are recomputed via dems_cal.compute_tpi / Horn + compute_twi_pyflwdir, based on the downsampled DEM.
    """
    extra: dict[str, Any] = {}
    if scale <= 1.0:
        h, w = bands[0].shape
        return bands, src_transform, w, h, extra

    h0, w0 = bands[0].shape
    out_w = max(1, int(w0 // scale))
    out_h = max(1, int(h0 // scale))
    dst_transform = src_transform * Affine.scale(float(scale), float(scale))
    crs_wkt = src_crs.to_wkt() if src_crs else ""
    crs_geo = dc.is_geographic_wkt(crs_wkt) if crs_wkt else False
    gt_gdal = _affine_to_gdal_gt(dst_transform)

    z_auto = (
        dc.compute_auto_z_factor(crs_wkt, gt_gdal, out_w, out_h)
        if crs_wkt
        else 1.0
    )
    z_use = float(args.z_factor) if getattr(args, "z_factor", 0) > 0 else float(z_auto)
    extra["z_factor_used"] = z_use

    dem_low = reproject_band_to_shape(
        bands[0], src_transform, src_crs, out_h, out_w, dst_transform
    )

    slope = demprocess_to_array(
        dem_low,
        crs_wkt,
        dst_transform,
        "slope",
        ["-compute_edges", "-s", str(z_use), "-p", "-of", "GTiff"],
    )
    aspect_deg = demprocess_to_array(
        dem_low,
        crs_wkt,
        dst_transform,
        "aspect",
        ["-compute_edges", "-s", str(z_use), "-zero_for_flat", "-of", "GTiff"],
    )
    hillshade = demprocess_to_array(
        dem_low,
        crs_wkt,
        dst_transform,
        "hillshade",
        [
            "-compute_edges",
            "-s",
            str(z_use),
            "-az",
            str(args.hillshade_azimuth),
            "-alt",
            str(args.hillshade_altitude),
            "-of",
            "GTiff",
        ],
    )

    nd = np.float32(np.nan)
    dem_valid = np.isfinite(dem_low)
    slope = slope.copy()
    aspect_deg = aspect_deg.copy()
    hillshade = hillshade.copy()
    slope[~dem_valid] = nd
    aspect_deg[~dem_valid] = nd
    hillshade[~dem_valid] = nd

    sin_a, cos_a = aspect_deg_to_sin_cos(aspect_deg, dem_valid)

    out_bands: list[np.ndarray] = [
        dem_low.astype(np.float32),
        slope,
        sin_a,
        cos_a,
        hillshade,
    ]

    nd_f = float(_SENTINEL_NODATA)
    dem_work = np.where(dem_valid, dem_low.astype(np.float64), nd_f)

    if raw_count >= 6:
        try:
            tpi_out = dc.compute_tpi(dem_work, nd_f, int(args.tpi_radius))
            if not args.no_tpi_range_clip:
                tpi_out = dc.clip_finite_to_range(
                    tpi_out,
                    float(args.tpi_clip_min),
                    float(args.tpi_clip_max),
                )
            tpi_out = tpi_out.astype(np.float32, copy=False)
            tpi_out[~dem_valid] = np.nan
            extra["tpi"] = {"source": "dems_cal.compute_tpi", "radius_px": int(args.tpi_radius)}
        except ImportError as e:
            tpi_out = np.full(dem_low.shape, np.nan, dtype=np.float32)
            extra["tpi"] = {"ok": False, "error": f"ImportError: {e}"}
        except Exception as e:
            tpi_out = np.full(dem_low.shape, np.nan, dtype=np.float32)
            extra["tpi"] = {"ok": False, "error": str(e)}
        out_bands.append(tpi_out)

    if raw_count >= 7:
        try:
            gx, gy = dc.horn_gradients_unitsafe(
                dem_work,
                dst_transform,
                nd_f,
                crs_geo,
                float(args.z_unit_scale),
            )
            slope_rad = np.arctan(np.hypot(gx, gy))
            slope_rad[~dem_valid] = np.nan
            twi_out = dc.compute_twi_pyflwdir(
                dem_work,
                nd_f,
                slope_rad,
                dst_transform,
                crs_geo,
                float(args.twi_min_slope_deg),
            )
            if not args.no_twi_range_clip:
                twi_out = dc.clip_finite_to_range(
                    twi_out,
                    float(args.twi_clip_min),
                    float(args.twi_clip_max),
                )
            twi_out = twi_out.astype(np.float32, copy=False)
            twi_out[~dem_valid] = np.nan
            fin = float(np.mean(np.isfinite(twi_out)))
            extra["twi"] = {
                "source": "dems_cal.horn_gradients + compute_twi_pyflwdir",
                "z_unit_scale": float(args.z_unit_scale),
                "twi_min_slope_deg": float(args.twi_min_slope_deg),
                "finite_fraction": fin,
            }
        except ImportError as e:
            twi_out = np.full(dem_low.shape, np.nan, dtype=np.float32)
            extra["twi"] = {"ok": False, "error": f"ImportError: {e}"}
        except Exception as e:
            twi_out = np.full(dem_low.shape, np.nan, dtype=np.float32)
            extra["twi"] = {"ok": False, "error": str(e)}
        out_bands.append(twi_out)

    return out_bands, dst_transform, out_w, out_h, extra


def _nan_to_file_nodata(arrays: list[np.ndarray], nodata: float) -> list[np.ndarray]:
    out: list[np.ndarray] = []
    nd = np.float32(nodata)
    for a in arrays:
        x = a.astype(np.float32, copy=True)
        x[~np.isfinite(x)] = nd
        out.append(x)
    return out


def write_physical_stack_tif(
    dst_path: Path,
    bands: list[np.ndarray],
    prof_out: dict,
    src_desc: tuple,
    raw_count: int,
    file_nodata_write: float,
    compress: str,
    blocksize: int,
) -> None:
    """Physical-quantity stack after downsampling / recomputation (without dems_norm); invalid pixels are written as file_nodata_write."""
    names = [_band_label(src_desc, i) for i in range(len(bands))]
    prof = prof_out.copy()
    prof.update(
        dtype="float32",
        count=len(bands),
        width=prof_out["width"],
        height=prof_out["height"],
        transform=prof_out["transform"],
    )
    arrays = _nan_to_file_nodata(bands, file_nodata_write)
    dn.write_multiband_tif(
        dst_path,
        arrays,
        prof,
        names,
        file_nodata_write,
        compress,
        blocksize,
        overwrite=True,
    )


def normalize_and_write_stack(
    bands: list[np.ndarray],
    prof_out: dict,
    file_nodata: float | None,
    raw_count: int,
    src_desc: tuple,
    dst_path: Path,
    args: argparse.Namespace,
) -> dict[str, Any]:
    """bands must have been processed by the second combined NoData rule pass already."""
    n_b = len(bands)

    meta: dict[str, Any] = {
        "bands": n_b,
        "min_bands_nodata_rule": int(args.min_bands_nodata),
        "downsample_scale": float(args.scale),
        "layers": {},
    }
    combined_arrays: list[np.ndarray] = []
    combined_names: list[str] = []

    b = bands[0]
    params: dict = {}
    out = dn.normalize_dem(b, params, mode=args.dem_mode)
    out[np.isnan(b)] = np.nan
    meta["layers"]["dem"] = params
    combined_arrays.append(out)
    combined_names.append(_band_label(src_desc, 0))

    b = bands[1]
    params = {}
    out = dn.normalize_slope_deg(b, params, mode=args.slope_mode, cap_deg=args.slope_cap)
    out[np.isnan(b)] = np.nan
    meta["layers"]["slope"] = params
    combined_arrays.append(out)
    combined_names.append(_band_label(src_desc, 1))

    for idx, key in ((2, "aspect_sin"), (3, "aspect_cos")):
        b = bands[idx]
        params = {}
        out = dn.normalize_aspect_trig(b, params, map_to_01=args.aspect_to_01)
        out[np.isnan(b)] = np.nan
        meta["layers"][key] = params
        combined_arrays.append(out)
        combined_names.append(_band_label(src_desc, idx))

    b = bands[4]
    params = {}
    out = dn.normalize_hillshade(b, params, mode=args.hillshade_mode)
    out[np.isnan(b)] = np.nan
    meta["layers"]["hillshade"] = params
    combined_arrays.append(out)
    combined_names.append(_band_label(src_desc, 4))

    if raw_count >= 6 and n_b >= 6:
        b = bands[5]
        params = {}
        out = dn.normalize_tpi(b, params, mode=args.tpi_mode)
        out[np.isnan(b)] = np.nan
        meta["layers"]["tpi"] = params
        combined_arrays.append(out)
        combined_names.append(_band_label(src_desc, 5))
    else:
        meta["layers"]["tpi"] = {"info": "missing_band6"}

    if raw_count >= 7 and n_b >= 7:
        b = bands[6]
        params = {}
        out = dn.normalize_twi(
            b,
            params,
            mode=args.twi_mode,
            log_before_clip=args.twi_norm_log,
        )
        out[np.isnan(b)] = np.nan
        meta["layers"]["twi"] = params
        combined_arrays.append(out)
        combined_names.append(_band_label(src_desc, 6))
    else:
        meta["layers"]["twi"] = {"info": "missing_band7"}

    prof_out = prof_out.copy()
    prof_out.update(
        count=len(combined_arrays),
        dtype="float32",
        width=prof_out["width"],
        height=prof_out["height"],
        transform=prof_out["transform"],
    )

    dn.write_multiband_tif(
        dst_path,
        combined_arrays,
        prof_out,
        combined_names,
        file_nodata,
        args.compress,
        args.blocksize,
        overwrite=True,
    )
    meta["output"] = str(dst_path)
    meta["band_descriptions"] = combined_names
    return meta


def process_stack(src_path: Path, dst_path: Path, args: argparse.Namespace) -> dict[str, Any]:
    (
        bands,
        prof,
        file_nodata,
        raw_count,
        src_desc,
        nodata_per_band,
        src_transform,
        src_crs,
    ) = read_stack_all_bands(src_path)
    if raw_count < 5:
        raise ValueError(
            f"At least 5 bands required (DEM / Slope / Aspect_sin / Aspect_cos / Hillshade); current {raw_count}"
        )

    bands = apply_multi_band_nodata_rule(
        bands,
        nodata_list_for_first_joint_rule(nodata_per_band, float(args.scale)),
        min_bands_nodata=args.min_bands_nodata,
    )

    down_extra: dict[str, Any] = {}
    if args.scale > 1.0:
        bands, dst_transform, out_w, out_h, down_extra = downsample_stack(
            bands, src_transform, src_crs, raw_count, float(args.scale), args
        )
        prof = prof.copy()
        prof.update(width=out_w, height=out_h, transform=dst_transform)
    else:
        pass

    # After downsampling, every band is recomputed / reprojected and invalid pixels are already NaN; using the source per-band nodata (e.g. TWI=0 with nodata=0)
    # would misclassify legitimate pixels as NoData or distort normalization percentiles. The second combined rule should judge by NaN only.
    nodata_for_rule: list[float | None] = (
        [None] * len(bands) if args.scale > 1.0 else list(nodata_per_band)
    )

    n_b = len(bands)
    nd_use = nodata_for_rule[:n_b]
    if len(nd_use) < n_b:
        nd_use = nd_use + [None] * (n_b - len(nd_use))
    bands = apply_multi_band_nodata_rule(
        bands,
        nd_use,
        min_bands_nodata=args.min_bands_nodata,
    )

    nd_write = float(file_nodata) if file_nodata is not None else float(_SENTINEL_NODATA)
    if not args.skip_without_norm:
        wpath = args.dst_without_norm.resolve()
        write_physical_stack_tif(
            wpath,
            bands,
            prof,
            src_desc,
            raw_count,
            nd_write,
            args.compress,
            args.blocksize,
        )

    meta = normalize_and_write_stack(
        bands,
        prof,
        file_nodata,
        raw_count,
        src_desc,
        dst_path,
        args,
    )
    meta["source"] = str(src_path)
    if not args.skip_without_norm:
        meta["output_without_norm"] = str(args.dst_without_norm.resolve())
    if down_extra:
        meta["downsample_topo"] = down_extra
    return meta


def main():
    ap = argparse.ArgumentParser(
        description="Multi-band terrain: optional downsampling + NoData -> write two multi-band GeoTIFFs: withoutnorm (physical units) and norm (normalized)"
    )
    ap.add_argument(
        "--src",
        type=Path,
        default=_DEFAULT_MERIT_STACK_DIR / _MERIT_1KM_STACK_NAME,
        help="Input multi-band GeoTIFF (Band 1 = DEM)",
    )
    ap.add_argument(
        "--dst",
        type=Path,
        default=_DEFAULT_MERIT_STACK_DIR / _MERIT_5KM_NORM_NAME,
        help="Output multi-band normalized GeoTIFF (default: Canada_Full_DEM_5km_MERIT_norm.tif)",
    )
    ap.add_argument(
        "--dst-without-norm",
        type=Path,
        default=_DEFAULT_MERIT_STACK_DIR / _MERIT_5KM_WITHOUT_NORM_NAME,
        dest="dst_without_norm",
        help="Output unnormalized physical-quantity stack (matches the raster before normalization; default: Canada_Full_DEM_5km_MERIT_withoutnorm.tif)",
    )
    ap.add_argument(
        "--skip-without-norm",
        action="store_true",
        dest="skip_without_norm",
        help="Do not write --dst-without-norm (write only the normalized result)",
    )
    ap.add_argument(
        "--scale",
        type=float,
        default=5.0,
        help="Downsample factor: when > 1, pixel side length becomes ~scale times larger (coarser resolution); 1 disables downsampling",
    )
    ap.add_argument(
        "--min-bands-nodata",
        type=int,
        default=2,
        help="Minimum number of NoData bands at a pixel for the entire pixel to be marked NoData (default: 2)",
    )

    ap.add_argument(
        "--dem-mode",
        choices=["log1p_p2p98", "minmax_p2p98", "robust_z"],
        default="log1p_p2p98",
        help="DEM normalization: log1p_p2p98 (recommended, mitigates right skew) / minmax_p2p98 / robust_z",
    )
    ap.add_argument(
        "--slope-mode",
        choices=["log1p_p2p98", "cap", "auto_p98", "minmax_p2p98"],
        default="log1p_p2p98",
        help="Slope normalization: log1p_p2p98 (recommended, mitigates severe right skew) / cap / auto_p98 / minmax_p2p98",
    )
    ap.add_argument("--slope-cap", type=float, default=10.0)
    ap.add_argument("--aspect-to-01", action="store_true", default=True)
    ap.add_argument("--aspect-keep-neg1_1", dest="aspect_to_01", action="store_false")
    ap.add_argument("--hillshade-mode", choices=["div255", "stretch_p1p99"], default="stretch_p1p99")
    ap.add_argument(
        "--tpi-mode",
        choices=["quantile_symmetric", "symmetric", "minmax_p2p98", "robust_z"],
        default="quantile_symmetric",
        help="TPI: quantile_symmetric (recommended, symmetric P2/P98 clip then (x+1)/2) / symmetric / minmax_p2p98",
    )
    ap.add_argument(
        "--twi-mode",
        choices=["clip_p1p99", "clip_p2p98", "minmax_p2p98", "robust_z"],
        default="clip_p2p98",
        help="TWI: clip_p2p98 (recommended, more stable) / clip_p1p99 / minmax_p2p98",
    )
    ap.add_argument(
        "--twi-norm-log",
        action="store_true",
        dest="twi_norm_log",
        help="Apply log(max(TWI, eps)) before clipping TWI; use only when values are positive and still skewed (already-log TWI typically does not need this)",
    )

    ap.add_argument("--compress", default="ZSTD", choices=["NONE", "LZW", "DEFLATE", "ZSTD"])
    ap.add_argument("--blocksize", type=int, default=512)
    ap.add_argument("--save-meta", type=Path, default=None)

    ap.add_argument(
        "--z-factor",
        type=float,
        default=0.0,
        help="GDAL DEMProcessing vertical scale -s; <= 0 auto-computes via dems_cal.compute_auto_z_factor",
    )
    ap.add_argument(
        "--hillshade-azimuth",
        type=float,
        default=315.0,
        dest="hillshade_azimuth",
        help="Hillshade azimuth (degrees), consistent with dems_cal's default",
    )
    ap.add_argument(
        "--hillshade-altitude",
        type=float,
        default=35.0,
        dest="hillshade_altitude",
        help="Hillshade altitude (degrees), consistent with dems_cal's default",
    )
    ap.add_argument(
        "--z-unit-scale",
        type=float,
        default=1.0,
        dest="z_unit_scale",
        help="DEM vertical-unit to meters (Horn slope for TWI); see dems_cal",
    )
    ap.add_argument(
        "--tpi-radius",
        type=int,
        default=5,
        dest="tpi_radius",
        help="TPI neighborhood half-width (pixels); window is (2r+1)^2",
    )
    ap.add_argument(
        "--twi-min-slope-deg",
        type=float,
        default=0.05,
        dest="twi_min_slope_deg",
        help="TWI slope lower bound (degrees)",
    )
    ap.add_argument(
        "--no-tpi-range-clip",
        action="store_true",
        dest="no_tpi_range_clip",
        help="Do not apply clip_finite_to_range to TPI",
    )
    ap.add_argument(
        "--tpi-clip-min",
        type=float,
        default=-5000.0,
        dest="tpi_clip_min",
    )
    ap.add_argument(
        "--tpi-clip-max",
        type=float,
        default=5000.0,
        dest="tpi_clip_max",
    )
    ap.add_argument(
        "--no-twi-range-clip",
        action="store_true",
        dest="no_twi_range_clip",
        help="Do not apply clip_finite_to_range to TWI",
    )
    ap.add_argument(
        "--twi-clip-min",
        type=float,
        default=-12.0,
        dest="twi_clip_min",
    )
    ap.add_argument(
        "--twi-clip-max",
        type=float,
        default=42.0,
        dest="twi_clip_max",
    )

    args = ap.parse_args()
    if args.min_bands_nodata < 1:
        ap.error("--min-bands-nodata must be >= 1")
    if args.scale <= 0:
        ap.error("--scale must be positive")
    if args.tpi_clip_min >= args.tpi_clip_max:
        ap.error("--tpi-clip-min must be less than --tpi-clip-max")
    if args.twi_clip_min >= args.twi_clip_max:
        ap.error("--twi-clip-min must be less than --twi-clip-max")
    if args.scale > 1.0 and gdal is None:
        raise SystemExit(
            f"--scale > 1 requires GDAL Python bindings (osgeo.gdal): {_GDAL_IMPORT_ERROR}"
        )

    src = args.src.resolve()
    dst = args.dst.resolve()
    if not src.is_file():
        raise SystemExit(f"Input does not exist: {src}")

    meta = process_stack(src, dst, args)
    if args.save_meta is not None:
        p = args.save_meta.resolve()
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps(meta, indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"[OK] parameters written to {p}")
    print(f"[OK] {src.name} -> {dst.name} ({len(meta.get('band_descriptions', []))} bands)")
    if not args.skip_without_norm:
        print(f"[OK] unnormalized -> {args.dst_without_norm.resolve().name}")


if __name__ == "__main__":
    main()
