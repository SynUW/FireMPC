# -*- coding: utf-8 -*-
"""
Multi-band terrain stack: optional downsampling -> unified NoData rules -> write both an **unnormalized** physical-quantity stack and a **normalized** stack (two GeoTIFFs).

Convention (consistent with dems_norm's stack mode):
  - Band 1 = DEM (unnormalized); Band 2 = Slope (degrees); Bands 3/4 = Aspect sin/cos;
    Band 5 = Hillshade; optional Band 6 = TPI, Band 7 = TWI.

Downsampling (--scale, default 5; > 1 enables it):
  - Band 1 DEM: bilinear-resampled to the coarse grid.
  - Bands 2-5: recomputed from the **downsampled DEM** via GDAL DEMProcessing (slope / aspect / hillshade);
    aspect is converted to sin and cos (consistent with the stack semantics); the original image's downsampled bands 2-5 are not used.
  - Bands 6/7 (if present): consistent with dems_cal.py, recomputed from the **downsampled DEM**:
    TPI = Z - neighborhood mean (scipy uniform_filter); TWI = ln(SCA / tan β), SCA = pyflwdir upstream area,
    β is Horn slope (radians).

Preprocessing:
  Apply NoData rules once at full resolution (when --scale > 1, only DEM does numeric nodata matching; bands 2-7 only treat NaN as invalid, to avoid TPI/TWI=0 colliding with nodata=0 and wiping out the whole DEM pixel);
  after downsampling, apply combined rules again at the output resolution.
  If >= min_bands_nodata bands are NoData at a pixel, set all bands to NaN at that pixel.
  Aspect sin/cos count as a single layer combined, to prevent flat-region simultaneous NaN on both from being mistaken for "two invalid bands" and erasing the entire pixel.

Normalization: call dems_norm.py; defaults are log1p-percentile for DEM/Slope, quantile_symmetric for TPI, clip_p2p98 for TWI.

Dependencies: rasterio, numpy, scipy; downsampling and TPI need scipy; TWI needs pyflwdir; GDAL bindings (osgeo.gdal).
"""

